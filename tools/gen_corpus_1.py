DOCS["acme_budget_management.md"] = """# 预算编制与执行管理办法

## 一、预算体系

公司预算分为经营预算、资本预算与现金流预算三类。经营预算按年度编制，按季度滚动复盘；资本预算按项目编制，跨年度项目应分年度列示。

预算单位为一级部门，二级部门预算并入一级部门统一管理。

## 二、编制流程

每年十月启动次年预算编制，各预算单位于十月三十一日前提交初稿。财务部于十一月十五日前完成汇总平衡，十一月三十日前提交预算委员会审议。

预算一经批准即具有约束力，原则上不得调整。确需调整的，应提交预算调整申请并说明原因。

## 三、执行与控制

预算执行率按季度考核，季度执行率低于百分之七十或高于百分之一百二十的，预算单位负责人须向财务部书面说明。

单笔支出超过对应预算科目余额的，系统自动拦截，须先完成预算调整方可支付。

## 四、分析与考核

财务部每月十日前出具预算执行分析报告。年度预算执行情况纳入部门负责人绩效考核，权重不低于百分之十。
"""

