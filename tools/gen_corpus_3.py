DOCS["acme_data_classification.md"] = """# 数据分级与保护规范

## 一、分级标准

数据分为公开、内部、机密、绝密四级。

公开数据可对外发布；内部数据仅限公司内部流转；机密数据包含客户信息、财务数据与人事薪酬数据，仅限授权人员访问；绝密数据包含核心算法、密钥材料与并购信息，访问须逐次审批。

## 二、保护措施

机密及以上数据须加密存储，传输须使用加密通道。对外提供机密数据须执行脱敏，脱敏规则按字段类型确定。

机密及以上数据的访问须留痕，日志保留不少于一百八十天。

## 三、出境与共享

数据出境须通过安全评估并签署数据处理协议。向第三方共享数据的，须进行供应商安全评估并在合同中约定数据安全责任条款。

## 四、销毁

数据达到保留期限后应销毁。机密及以上数据销毁须采用不可恢复的方式，并留存销毁记录。员工离职时其个人工作数据按分级处理，机密数据不得由个人带走。
"""

