DOCS["acme_performance.md"] = """# 绩效管理办法

## 一、考核周期与对象

绩效考核按季度与年度两个周期开展。季度考核面向全体正式员工，年度考核结果作为调薪、晋升与年终奖发放的主要依据。

试用期内员工参加季度考核，但不参加年度考核排名。

## 二、评价指标

考核由业绩指标与行为指标两部分构成，权重分别为百分之七十与百分之三十。业绩指标应在考核周期开始前由直属上级与员工共同确认。

行为指标包括协作、责任心、专业能力与价值观践行四个维度，采用行为锚定法评分。

## 三、等级分布

考核结果分为 A、B、C、D 四档，其中 A 档比例不超过部门人数的百分之十五，C 档与 D 档合计不低于百分之十。

部门人数少于八人的，可不强制分布，但须说明评定理由。

## 四、结果应用

年度考核为 A 的员工优先纳入晋升候选与关键人才培养计划。连续两个年度考核为 D 的，公司可依法调整岗位或解除劳动合同。

员工对考核结果有异议的，可在结果告知后五个工作日内向人力资源部提起申诉。
"""

DOCS["acme_recruitment.md"] = """# 招聘与录用流程

## 一、需求审批

用人部门提交招聘需求时应明确岗位职责、任职要求、编制来源与到岗时间。新增编制须经人力资源部与分管副总审批，替换编制由人力资源部备案即可。

## 二、面试流程

标准面试流程为初试、复试与终面三轮。技术岗位增加技术测评环节，管理岗位增加案例面试环节。

面试官应在面试结束后一个工作日内提交评价意见，评价意见须包含具体行为事例，不得仅使用"尚可""一般"等模糊表述。

## 三、背景调查

拟录用人员须通过背景调查，调查内容包括工作履历、离职原因与学历学位真实性。关键岗位与涉密岗位增加征信与合规记录查询。

背景调查发现与候选人陈述不符的，取消录用资格。

## 四、录用与offer

录用审批通过后由人力资源部发放录用通知函，通知函应载明岗位、职级、薪酬构成、报到时间与失效条件。

候选人接受 offer 后违约的，纳入招聘黑名单，一年内不再考虑。

## 五、内推奖励

内部推荐成功的，推荐人可获得内推奖金，标准为被推荐人转正后发放三千元至一万元，具体按岗位紧缺程度确定。
"""

